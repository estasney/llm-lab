import json
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

import yaml
from pydantic import BaseModel, ConfigDict, Field

from llm_lab.datasets.recipe import PortableRecipe, Recipe


class RunFilePaths(BaseModel):
    model_config = ConfigDict(frozen=True, validate_by_name=True, serialize_by_alias=True)

    parquet_files: tuple[str, ...] = Field(
        validation_alias="parquet-files", serialization_alias="parquet-files", min_length=1
    )
    processor_files: dict[str, tuple[str, ...]] = Field(
        validation_alias="processor-files", serialization_alias="processor-files", default_factory=dict
    )


class RunMetadata(BaseModel):
    model_config = ConfigDict(frozen=True)

    actual_num_records: int
    target_num_records: int
    file_paths: RunFilePaths


class RepositoryFilePaths(BaseModel):
    model_config = ConfigDict(frozen=True, validate_by_name=True, serialize_by_alias=True)

    data: tuple[str, ...]
    processor_files: dict[str, tuple[str, ...]] = Field(
        validation_alias="processor-files", serialization_alias="processor-files", default_factory=dict
    )


class RepositoryMetadata(BaseModel):
    model_config = ConfigDict(frozen=True)

    actual_num_records: int
    target_num_records: int
    file_paths: RepositoryFilePaths


@dataclass(frozen=True)
class GeneratedRun:
    directory: Path
    metadata: RunMetadata
    image_paths: tuple[str, ...]


def read_generated_run(directory: Path) -> GeneratedRun:
    images = directory / "images"
    return GeneratedRun(
        directory=directory,
        metadata=RunMetadata.model_validate_json((directory / "metadata.json").read_text()),
        image_paths=tuple(sorted(path.relative_to(images).as_posix() for path in images.rglob("*") if path.is_file())),
    )


def name_run_file(run_id: str, folder: str, path: str) -> str:
    return f"{folder}/{run_id}-{PurePosixPath(path).name}"


def add_run_to_metadata(run_id: str, run: RunMetadata, stored: RepositoryMetadata) -> RepositoryMetadata:
    run_processor_files = {
        name: tuple(name_run_file(run_id, name, path) for path in paths)
        for name, paths in run.file_paths.processor_files.items()
    }
    processor_names = sorted(stored.file_paths.processor_files.keys() | run_processor_files.keys())
    return RepositoryMetadata(
        actual_num_records=stored.actual_num_records + run.actual_num_records,
        target_num_records=stored.target_num_records + run.target_num_records,
        file_paths=RepositoryFilePaths(
            data=(
                *stored.file_paths.data,
                *(name_run_file(run_id, "data", path) for path in run.file_paths.parquet_files),
            ),
            processor_files={
                name: (*stored.file_paths.processor_files.get(name, ()), *run_processor_files.get(name, ()))
                for name in processor_names
            },
        ),
    )


def write_dataset_card(name: str, metadata: RepositoryMetadata, recipe: Recipe) -> str:
    configs = [
        {"config_name": "data", "data_files": "data/*.parquet", "default": True},
        *(
            {"config_name": processor, "data_files": f"{processor}/*.parquet"}
            for processor in metadata.file_paths.processor_files
        ),
    ]
    header = yaml.safe_dump({"configs": configs, "tags": ["synthetic", "datadesigner"]}, sort_keys=False)
    return (
        f"---\n{header}---\n\n# {name}\n\n"
        f"{metadata.actual_num_records:,} rows generated by llm-lab with `{recipe.served_model}` served by vLLM.\n\n"
        "`recipe.yaml` holds the recipe of the rows and `metadata.json` lists the data files.\n"
    )


def plan_repository_files(
    name: str, run_id: str, run: GeneratedRun, stored: RepositoryMetadata, recipe: PortableRecipe
) -> Mapping[str, Path | bytes]:
    metadata = add_run_to_metadata(run_id, run.metadata, stored)
    run_files = {
        **{name_run_file(run_id, "data", path): run.directory / path for path in run.metadata.file_paths.parquet_files},
        **{
            name_run_file(run_id, processor, path): run.directory / path
            for processor, paths in run.metadata.file_paths.processor_files.items()
            for path in paths
        },
        **{f"images/{path}": run.directory / "images" / path for path in run.image_paths},
    }
    return {
        **run_files,
        "builder_config.json": run.directory / "builder_config.json",
        "metadata.json": json.dumps(metadata.model_dump(mode="json"), indent=2).encode(),
        "README.md": write_dataset_card(name, metadata, recipe.recipe).encode(),
        "recipe.yaml": recipe.recipe.source.encode(),
    }
