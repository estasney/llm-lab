from pathlib import Path
from typing import Annotated, Protocol

from data_designer.integrations.huggingface.client import HuggingFaceHubClient
from huggingface_hub import HfApi
from pydantic import BaseModel, ConfigDict, SecretStr, StringConstraints

from llm_lab.datasets.recipe import Recipe
from llm_lab.jobs.protocol import JobName

type HubNamespace = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9]+([._-][A-Za-z0-9]+)*$", max_length=96)]


class HubDataset(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")

    namespace: HubNamespace
    name: JobName

    @property
    def repo_id(self) -> str:
        return f"{self.namespace}/{self.name}"


def parse_hub_dataset(repo_id: str) -> HubDataset:
    match repo_id.split("/"):
        case [namespace, name]:
            return HubDataset(namespace=namespace, name=name)
        case _:
            raise ValueError(f"{repo_id!r} is not a repository id of the form <namespace>/<name>")


class DatasetHub(Protocol):
    def exists(self, dataset: HubDataset) -> bool: ...

    def publish(self, dataset: HubDataset, directory: Path, recipe: Recipe) -> str: ...


class HuggingFaceHub:
    def __init__(self, token: SecretStr | None) -> None:
        self.token = None if token is None else token.get_secret_value()
        self.api = HfApi(token=self.token)

    def exists(self, dataset: HubDataset) -> bool:
        return self.api.repo_exists(dataset.repo_id, repo_type="dataset")

    def publish(self, dataset: HubDataset, directory: Path, recipe: Recipe) -> str:
        url = HuggingFaceHubClient(token=self.token).upload_dataset(
            repo_id=dataset.repo_id,
            base_dataset_path=directory,
            description=f"Generated by llm-lab with `{recipe.served_model}` served by vLLM.",
            private=True,
        )
        self.api.upload_file(
            path_or_fileobj=recipe.source.encode(),
            path_in_repo="recipe.yaml",
            repo_id=dataset.repo_id,
            repo_type="dataset",
            commit_message="Add the llm-lab recipe",
        )
        return url
